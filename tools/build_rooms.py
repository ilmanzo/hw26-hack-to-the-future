#!/usr/bin/env python3
"""Generate assets/rooms.h (the room data for src/room.c) from the rooms in tools/check_rooms.py.

    python3 tools/build_rooms.py assets/rooms.h

Only rooms the game can play are emitted: a gate, and only drone foes ('d'). Every room is checked
for reachability first; an unreachable room stops the build.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_rooms

FOE_TYPES = {"d": "FOE_DRONE"}


def playable(room):
    return room.gate is not None and all(f[0] in FOE_TYPES for f in room.foes)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "assets/rooms.h"
    rooms = [r for r in check_rooms.ROOMS if playable(r)]
    for r in rooms:
        bad = r.problems()
        if bad:
            sys.exit(f"build_rooms.py: room '{r.name}' is not reachable: " + ", ".join(bad))
    lines = ["// Generated by tools/build_rooms.py from tools/check_rooms.py. Do not edit.",
             "#ifndef ROOMS_H", "#define ROOMS_H", "",
             "struct Rect { unsigned char r0, r1, c0, c1; };            // solid tiles, inclusive",
             "struct Foe { unsigned char type, row, c0, c1; };          // patrols columns c0..c1 at row",
             "struct RoomDef {",
             "    const struct Rect *rects; unsigned char n_rects;",
             "    const unsigned char *terms; unsigned char n_terms;    // (surface row, left column) pairs",
             "    unsigned char gate_row, gate_col, gate_w;             // gate stands on gate_row, 3 tiles tall",
             "    unsigned char start_row, start_col;                   // Geeko stands on start_row",
             "    const struct Foe *foes; unsigned char n_foes;",
             "};", "", "#define FOE_DRONE 1", ""]
    for i, r in enumerate(rooms):
        lines.append(f"// {r.name}")
        lines.append(f"static const struct Rect room{i}_rects[] = {{ " + ", ".join(
            "{%d, %d, %d, %d}" % rect for rect in r.rects_list) + " };")
        lines.append(f"static const unsigned char room{i}_terms[] = {{ " + ", ".join(
            f"{row}, {col}" for row, col in r.terminals) + " };")
        lines.append(f"static const struct Foe room{i}_foes[] = {{ " + ", ".join(
            "{%s, %d, %d, %d}" % (FOE_TYPES[f[0]], f[1], f[2], f[3]) for f in r.foes) + " };")
    lines.append("")
    lines.append("static const struct RoomDef room_defs[] = {")
    for i, r in enumerate(rooms):
        lines.append(f"    {{ room{i}_rects, {len(r.rects_list)}, room{i}_terms, {len(r.terminals)}, "
                     f"{r.gate[0]}, {r.gate[1]}, {r.gate[2]}, {r.start[0]}, {r.start[1]}, "
                     f"room{i}_foes, {len(r.foes)} }},")
    lines += ["};", f"#define N_ROOMS {len(rooms)}", "", "#endif // ROOMS_H", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"[OK] Generated {out} ({len(rooms)} room(s))")


if __name__ == "__main__":
    main()
