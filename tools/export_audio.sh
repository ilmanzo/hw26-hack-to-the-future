#!/bin/bash
# Regenerate assets/audio/chill.s and assets/audio/sfx.s (FamiTone2 data) from chill.ftm and sfx.txt.
# FamiStudio runs headless in a container (it needs GTK and a display, hence Xvfb). Needs podman + curl.
set -euo pipefail
cd "$(dirname "$0")/.."

VER=4.5.3
ZIP=FamiStudio453-LinuxAMD64.zip
ZIP_SHA256=9133afed2fb384663b0735d8e950cdc2714849f4fd476b16de8d56e5e81da0ad
CACHE=${FAMISTUDIO_CACHE:-$HOME/.cache/famistudio}
IMG=famistudio-run

if [ ! -f "$CACHE/app/FamiStudio.dll" ]; then
    mkdir -p "$CACHE/app"
    curl -fsSL -o "$CACHE/$ZIP" "https://github.com/BleuBleu/FamiStudio/releases/download/$VER/$ZIP"
    echo "$ZIP_SHA256  $CACHE/$ZIP" | sha256sum -c -
    unzip -q -o "$CACHE/$ZIP" -d "$CACHE/app"
fi

if ! podman image exists "$IMG"; then
    cf=$(mktemp)
    cat > "$cf" <<'DOCKER'
FROM mcr.microsoft.com/dotnet/runtime:8.0
RUN apt-get update && apt-get install -y --no-install-recommends \
    libgtk-3-0 xvfb xauth libgl1 libglu1-mesa libopenal1 libx11-6 libxcursor1 libxrandr2 libxi6 libxinerama1 \
    ca-certificates && rm -rf /var/lib/apt/lists/*
DOCKER
    podman build -t "$IMG" -f "$cf" .
    rm -f "$cf"
fi

out=$(mktemp -d)
fs() {  # FamiStudio <input> <command> <output> [options], paths inside the container: /a = assets/audio, /o = temp dir
    podman run --rm -v "$(readlink -f "$CACHE/app")":/fs:ro,Z -v "$PWD/assets/audio":/a:ro,Z -v "$out":/o:Z "$IMG" \
        sh -c "cd /tmp && xvfb-run -a dotnet /fs/FamiStudio.dll $*"
}
fs /a/chill.ftm famitone2-asm-export /o/chill.s -famitone2-asm-format:ca65
fs /a/sfx.txt famitone2-asm-sfx-export /o/sfx.s -famitone2-asm-format:ca65

# ca65 -> LLVM assembler: '@' local labels become '.L', drop the ca65-only .export / .global lines.
for pair in chill:chill.ftm sfx:sfx.txt; do
    n=${pair%%:*}; src=${pair##*:}
    { echo "; Generated by tools/export_audio.sh from assets/audio/$src (FamiStudio $VER). Do not edit."
      sed -e 's/@/.L/g' -e '/^\.export/d' -e '/^\.global/d' "$out/$n.s"; } > "assets/audio/$n.s"
done
rm -rf "$out"
echo "wrote assets/audio/chill.s assets/audio/sfx.s"
